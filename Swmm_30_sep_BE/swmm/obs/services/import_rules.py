def resolve_pattern_sources(pattern_numbers):
    """Cross-check many pattern numbers against the four sources of truth in ONE pass.

    Returns `{NORMALISED pattern number: PatternSource}`, carrying an entry only for a
    code that matched. A code absent from the result matched nothing.

    This is the batching decision, stated in the API Contract Block: a fifty-row sheet
    issues at most FOUR queries, one per source table, not fifty. The single-value form
    below is written in terms of this one, so there is exactly one lookup in the codebase
    and `verify_pattern` and the import cannot drift apart.

    Developed by Unknown: MATCHING IS NOW SPACE-INSENSITIVE ON BOTH SIDES. It was previously
    trimmed and upper-cased, so a stored `SR6001D 921 62` and a typed `SR6001D-921-62` with
    the spaces closed up were two different codes and the row was failed. Both sides now go
    through `normalise_item_code`: the workbook value in Python, the two live tables through
    the equivalent SQL expression, and the two SOT tables not at all because the seeder wrote
    them normalised already.

    The KEYS OF THE RETURNED DICT ARE NORMALISED CODES. Callers must key into it with
    `normalise_item_code`, not with `.strip().upper()` - `resolve_pattern_source` below and
    `SparesImportMixin._classify_import_rows` both do.
    """
    codes = set()
    for pattern_number in pattern_numbers:
        code = normalise_item_code(pattern_number)
        if code:
            codes.add(code)
    if not codes:
        return {}

    resolved = {}

    def take(
        queryset,
        source,
        description_field,
        category_field,
        denomination_field,
        stored_normalised=False,
    ):
        outstanding = codes - resolved.keys()
        if not outstanding:
            return
        if stored_normalised:
            # The two SOT tables. `item_code` IS the normalised code, so no per-row
            # expression is needed and the primary key index answers the lookup directly.
            rows = queryset.filter(item_code__in=outstanding)
        else:
            rows = queryset.annotate(
                _code=_normalised_item_code_expression()
            ).filter(_code__in=outstanding)
        for row in rows:
            code = normalise_item_code(row.item_code)
            if not code:
                continue
            # First hit wins, and rows arrive in no guaranteed order - a table whose
            # `item_code` is not unique (`WLMS_wlmsspare` is not) can hand back two rows
            # for one code, so the first one seen is kept and the rest ignored.
            if code in resolved:
                continue
            resolved[code] = _pattern_source(
                source,
                row.item_code,
                getattr(row, description_field, None) if description_field else None,
                getattr(row, category_field, None),
                getattr(row, denomination_field, None) if denomination_field else None,
            )

    # `DatabaseError` is the whole realistic failure surface here and it is caught
    # specifically rather than with a bare `except` - it already covers a dead connection
    # (`OperationalError`) and a table that does not exist because the migration has not
    # been applied (`ProgrammingError`), which is the live risk while the two new
    # source-of-truth tables are being rolled out.
    try:
        take(
            Item.objects.all(),
            PATTERN_SOURCE_ITEM,
            "item_desc",
            "crp_category",
            "item_deno",
        )
        # Developed by Unknown: The two SOT tables pass `None` for the description field.
        # `item_desc` has been dropped from both - neither seeding file carries a
        # description - so a SOT hit corrects CATEGORY and nothing else. `_pattern_source`
        # and `apply_source_of_truth` already treat an absent description as "leave the
        # workbook's own value alone", so this needed no further change.
        take(
            MOItemSourceOfTruth.objects.all(),
            PATTERN_SOURCE_MO_SOT,
            None,
            "crp_category",
            None,
            stored_normalised=True,
        )
        take(
            WLMSSpare.objects.all(),
            PATTERN_SOURCE_WLMS,
            "item_desc",
            "category",
            "denom_id",
        )
        take(
            WedItemSourceOfTruth.objects.all(),
            PATTERN_SOURCE_WED_SOT,
            None,
            "crp_category",
            None,
            stored_normalised=True,
        )
    except DatabaseError as error:
        raise PatternSourceUnavailable(PATTERN_LOOKUP_FAILED_MESSAGE) from error

    return resolved


def resolve_pattern_source(pattern_number):
    """The single-value form of `resolve_pattern_sources`, for `verify_pattern`.

    Returns a `PatternSource` or `None`. Exists so the Add Spare form, the IIF cart and the
    import all read the same four tables in the same order - doctrine hard rule 5.

    Developed by Unknown: keyed with `normalise_item_code` and not `.strip().upper()`, because
    that is now what `resolve_pattern_sources` keys its result by. Keying it the old way
    returned `None` for every code carrying an internal space - a match found in the database
    and then thrown away on the way out.
    """
    code = normalise_item_code(pattern_number)
    if not code:
        return None
    return resolve_pattern_sources([code]).get(code)


# Developed by Unknown: How many near matches an unrecognised pattern number is offered. A
# named constant and not a literal, so the number can be changed in one place.
#
# Five, and not the whole candidate list. The change prompt asked for every source-of-truth
# code sharing any four-character window with the typed code, uncapped. Measured against the
# seeded data that is unusable: the window `6001` occurs in 12,980 ILMS codes and `SR60` in
# 12,746, so one mistyped `SR6001D-...` would put roughly thirteen thousand codes into a table
# cell. The window stays the recall mechanism; the floor and this cap are what make the
# output readable. THIS IS A DEVIATION FROM THE PROMPT AND IS RECORDED AS ONE.
PATTERN_SUGGESTION_LIMIT = 5

# Developed by Unknown: The width of the contiguous window the prompt specifies for recall.
PATTERN_SUGGESTION_WINDOW = 4

# Developed by Unknown: The floor a candidate must clear before it is offered at all - a
# common run of at least six characters, OR at least three distinct shared windows. This is
# what stops a single shared window such as `6001` qualifying thousands of codes.
PATTERN_SUGGESTION_MIN_SUBSTRING = 6
PATTERN_SUGGESTION_MIN_WINDOWS = 3

# Developed by Unknown: How many rows the trigram pass hands to the Python ranking, per failed
# code. The database is asked for the most similar candidates and the exact ranking below is
# then computed over a bounded set, rather than the longest-common-substring being expressed
# in SQL. Fifty is comfortably wider than the five that survive.
PATTERN_SUGGESTION_CANDIDATES = 50

# Developed by Unknown: Below this trigram similarity a candidate is not worth ranking. It is
# deliberately loose - the floor above is the real filter, and this only bounds the scan.
PATTERN_SUGGESTION_MIN_SIMILARITY = 0.3


def _code_windows(code):
    """Every contiguous `PATTERN_SUGGESTION_WINDOW`-character window of a normalised code."""
    width = PATTERN_SUGGESTION_WINDOW
    if len(code) < width:
        return frozenset()
    return frozenset(code[index:index + width] for index in range(len(code) - width + 1))


def _longest_common_substring_length(left, right):
    """Length of the longest run of characters the two codes share, contiguously.

    Developed by Unknown: the ordinary dynamic-programming form, kept to one row of state
    because only the length is wanted and never the substring itself. It runs over at most
    `PATTERN_SUGGESTION_CANDIDATES` pairs per failed row, on strings averaging 18 characters,
    so the quadratic cost is not worth avoiding here.
    """
    if not left or not right:
        return 0
    previous = [0] * (len(right) + 1)
    best = 0
    for left_index in range(1, len(left) + 1):
        current = [0] * (len(right) + 1)
        for right_index in range(1, len(right) + 1):
            if left[left_index - 1] == right[right_index - 1]:
                current[right_index] = previous[right_index - 1] + 1
                if current[right_index] > best:
                    best = current[right_index]
        previous = current
    return best


# Developed by Unknown: The two tables the suggestions are drawn from, and the label each
# carries so the screen can say where a suggested code came from.
#
# BOTH tables are searched, rather than the one "table family" of the import. The prompt asks
# for family scoping, but this import screen has no family: `resolve_pattern_sources` checks
# all four sources for every row, and a workbook is not declared to be an ILMS workbook or a
# WLMS one. Scoping to a family here would mean inventing a distinction the screen does not
# make. RECORDED AS A DEVIATION.
PATTERN_SUGGESTION_SOURCES = (
    (MOItemSourceOfTruth, PATTERN_SOURCE_MO_SOT),
    (WedItemSourceOfTruth, PATTERN_SOURCE_WED_SOT),
)


def _trigram_candidates_for_codes(model, codes, *, limit_per_code, min_similarity):
    """`{code: [(candidate, similarity), ...]}` for EVERY code, from one table, in ONE query.

    Developed by Unknown: the previous shape called `TrigramSimilarity(...).order_by(...)[:N]`
    once PER CODE - correct in isolation, but N codes made N queries against a table this size,
    and a validation preview is exactly the screen where N is large (it is the failed rows,
    which a first import of a real sheet has plenty of). This gets the same per-code "closest N"
    ranking in exactly one round trip regardless of how many codes are being looked up: `unnest`
    explodes the code list into rows, and the `LATERAL` subquery re-runs the GIN-trgm-indexed
    similarity ranking once per exploded row, table-side, in the same query plan.
    """
    if not codes:
        return {}
    column = model._meta.get_field("item_code").column
    quoted_table = connection.ops.quote_name(model._meta.db_table)
    quoted_column = connection.ops.quote_name(column)
    # Developed by Unknown: `%` IS THE INDEXED OPERATOR, `similarity() >=` IS NOT. The GIN
    # `gin_trgm_ops` index on this column (see the model's `Meta.indexes`) supports pg_trgm's
    # `%` "is this similar" operator directly - that is the one thing a trigram GIN index is
    # FOR - but it does not support an index scan ordered by, or filtered on, the bare
    # `similarity()` function call. A `WHERE similarity(...) >= x` predicate, which is what
    # this used to be, cannot use that index at all and forces a sequential scan computing
    # `similarity()` for every row of a ~1M-row table, per code. `%`'s own threshold is the
    # session GUC `pg_trgm.similarity_threshold`, so it is set here, on this connection, to
    # match `PATTERN_SUGGESTION_MIN_SIMILARITY` exactly rather than trusting Postgres's
    # default (also 0.3, but a default is not a guarantee).
    sql = f"""
        SELECT c.code, ranked.candidate, ranked.similarity
        FROM unnest(%s::text[]) AS c(code)
        CROSS JOIN LATERAL (
            SELECT {quoted_column} AS candidate,
                   similarity({quoted_column}, c.code) AS similarity
            FROM {quoted_table}
            WHERE {quoted_column} %% c.code
            ORDER BY similarity DESC
            LIMIT %s
        ) AS ranked
    """
    # Developed by Unknown: `SET LOCAL` only holds for the current transaction - outside one,
    # under Django's ordinary autocommit, it would commit and reset before the SELECT below
    # ever ran, silently falling back to Postgres's own default threshold. `transaction.atomic()`
    # is what makes "local" mean anything here; this block writes nothing, so wrapping a read in
    # a transaction costs nothing it was not already going to pay as an implicit one.
    with transaction.atomic(), connection.cursor() as cursor:
        cursor.execute("SET LOCAL pg_trgm.similarity_threshold = %s", [min_similarity])
        cursor.execute(sql, [list(codes), limit_per_code])
        rows = cursor.fetchall()
    candidates_by_code = {}
    for code, candidate, similarity in rows:
        candidates_by_code.setdefault(code, []).append((candidate, similarity))
    return candidates_by_code


def suggest_item_codes(pattern_numbers):
    """Near matches for pattern numbers that matched NOTHING, in one batched pass.

    Returns `{normalised code: [suggested code, ...]}`, at most `PATTERN_SUGGESTION_LIMIT`
    each, best first. A code with no candidate clearing the floor is absent from the result.

    Called ONLY for the rows that failed. A sheet where every pattern number resolved issues
    no query at all, and a sheet with any number of unknown codes issues exactly two - one per
    source table, via `_trigram_candidates_for_codes` - never one per code.

    Returns `{}` rather than raising when the trigram search is unavailable. A suggestion is
    a convenience and its absence must never fail an import: `resolve_pattern_sources` is
    what fails closed, and it has already run by the time this is called.
    """
    codes = set()
    for pattern_number in pattern_numbers:
        code = normalise_item_code(pattern_number)
        if code:
            codes.add(code)
    if not codes:
        return {}

    try:
        candidates_by_source = {
            source: _trigram_candidates_for_codes(
                model,
                codes,
                limit_per_code=PATTERN_SUGGESTION_CANDIDATES,
                min_similarity=PATTERN_SUGGESTION_MIN_SIMILARITY,
            )
            for model, source in PATTERN_SUGGESTION_SOURCES
        }
    except DatabaseError:
        return {}

    suggestions = {}
    for code in codes:
        windows = _code_windows(code)
        ranked = []
        for _model, source in PATTERN_SUGGESTION_SOURCES:
            for candidate, similarity in candidates_by_source[source].get(code, []):
                if candidate == code:
                    continue
                shared = len(windows & _code_windows(candidate))
                common = _longest_common_substring_length(code, candidate)
                if (
                    common < PATTERN_SUGGESTION_MIN_SUBSTRING
                    and shared < PATTERN_SUGGESTION_MIN_WINDOWS
                ):
                    continue
                # Negated so a plain ascending sort gives longest-run first, then most
                # shared windows, then most similar, then the code itself ascending -
                # which is what makes the order stable across runs.
                ranked.append((-common, -shared, -float(similarity), candidate))
        if ranked:
            ranked.sort()
            # A code present in BOTH source-of-truth tables would otherwise be offered
            # twice, which reads as two suggestions and is one.
            offered = []
            for *_ignored, candidate in ranked:
                if candidate in offered:
                    continue
                offered.append(candidate)
                if len(offered) == PATTERN_SUGGESTION_LIMIT:
                    break
            suggestions[code] = offered
    return suggestions


# Developed by Unknown: The longest description this application can store. Read from the
# field rather than written as 1000, so the two cannot drift.
DESCRIPTION_MAX_LENGTH = Spares._meta.get_field("description").max_length


def apply_source_of_truth(row, source):
    """Correct one row's DESCRIPTION and CATEGORY from the source of truth that matched it.

    Returns `(corrected_row, corrections)`. `corrected_row` is a COPY - the caller's row is
    never mutated, so the original workbook values stay available for the wire.

    This runs BEFORE the rule engine, deliberately. A blank DESCRIPTION is a hard reject
    under rule 2.8, and clause 4.4 makes the source of truth's description mandatory where
    the pattern number matched - so filling the cell first is what lets such a row pass on
    the authority's own value rather than failing on an omission the authority can settle.

    Two values are deliberately NOT written:
      - a source description longer than the column can hold. Silently truncating an
        authoritative description is worse than leaving the workbook's own, so the row keeps
        what it had and no correction is recorded.
      - a category this application has no name for (`source_category` returned `None`).
    """
    corrected = dict(row)
    corrections = []
    if source is None:
        return corrected, corrections

    original_description = cell_text(row.get("description")).strip()
    # Developed by Unknown: The applied value is normalised to what rules 2.1, 2.3 and 2.4
    # require - upper case, no surrounding spaces, no doubled internal space - because the
    # engine runs over the CORRECTED row immediately after this. Without the collapse, a
    # source description holding two spaces between two words would fail rule 2.3 on a
    # value the application itself wrote, and the user would have no way to fix it: the
    # source of truth is the authority and the workbook cell is being overwritten from it.
    source_description = " ".join((source.description or "").split()).upper()
    if (
        source_description
        and len(source_description) <= DESCRIPTION_MAX_LENGTH
        and source_description != original_description.upper()
    ):
        corrected["description"] = source_description
        corrections.append(
            FieldCorrection(
                "description",
                original_description,
                source_description,
                source.source,
            )
        )

    original_category = cell_text(row.get("category")).strip().upper()
    if source.category is not None:
        # The workbook writes the single letter, the model stores the full word - so the
        # row's own `P` and the source's `PERMANENT` are the same answer and are not a
        # correction. `CATEGORY_BY_SOURCE_CODE` maps both onto one value for the comparison.
        original_mapped = source_category(original_category)
        if original_mapped != source.category:
            corrected["category"] = source.category
            corrections.append(
                FieldCorrection(
                    "category", original_category, source.category, source.source
                )
            )

    return corrected, corrections


def check_pattern_source(row, source, errors):
    """Rule the register does not number - a typed pattern number that matched nothing.

    An EMPTY cell is not checked and is not an error: clause 2.7.1 says a ship's staff who
    do not know the INCATted pattern number must leave the cell empty, and that row is
    auto-generated instead. Returns the row's match state - `True`, `False`, or `None` where
    there was nothing to check.
    """
    if not cell_text(row.get("pattern_number")).strip():
        return None
    if source is None:
        errors.setdefault("pattern_number", []).append(
            RULE_MESSAGES["PATTERN-NOT-FOUND"]
        )
        return False
    return True


def is_pattern_only_failure(errors):
    """True when the ONLY thing wrong with this row is a pattern number nothing recognises.

    Developed by Unknown: The row is still not committable - clause 4.3 is unchanged and no
    wrong pattern number reaches the spares table - but it must not be PAINTED like a row that
    breached a rule of the document. A rating who left one cell for the storekeeper to look up
    is not the same as a rating who entered a denomination that does not exist, and the working
    table said the same thing about both: a red band across all twenty columns. The front end
    reads this flag and tints such a row apart, leaving the red on the PATTERN NUMBER cell where
    `check_pattern_source` put it.

    THE MESSAGE IS CHECKED AND NOT ONLY THE FIELD, which is the whole of the care needed here.
    `R-019` - a `/` or a `\\` in the pattern number, clause 2.7.4 - lands on this same key, and
    that IS a breach of the document. Keying on the field alone would quietly soften it.
    """
    if not errors or set(errors) != {"pattern_number"}:
        return False
    return list(errors["pattern_number"]) == [RULE_MESSAGES["PATTERN-NOT-FOUND"]]


def is_swmm_generated_pattern_number(pattern_number, ship_customer_code):
    """Was this pattern number minted by SWMM rather than typed from an MO or WED item code?

    Decided BY THE PREFIX, which is the whole of the test and needs nothing stored. Every
    number `obs.utils.generate_pattern_number` produces is
    `{ship customer code}-{SPAR}{EQUI}{NNNNNN}`, so a pattern number beginning with this
    ship's customer code and a hyphen is one the application generated. A typed MO or WED
    item code does not carry that prefix - if it did it would have had to match a source of
    truth to get this far, and the sources of truth hold item codes, not SWMM's own numbers.
    """
    code = (ship_customer_code or "").strip().upper()
    if not code:
        return False
    return (pattern_number or "").strip().upper().startswith(f"{code}-")


