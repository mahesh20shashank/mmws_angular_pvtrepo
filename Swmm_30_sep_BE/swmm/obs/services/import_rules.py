def import_ship_customer_code():
    """The ship's adopted MO customer code, upper-cased, for the reconciliation above.

    Raises `PatternSourceUnavailable` carrying `NO_SHIP_MESSAGE` when none has been adopted.

    Developed by Unknown: this used to read `master.utils.get_this_ship().customer_code`, which
    is written by nothing but the CMMS sync and is therefore blank on every fresh install - so
    every import was refused before a row was read. It now reads the code the FIRST workbook
    adopted, through `_resolve_adopted_ship_customer_code` below, which is the single resolver
    both this module and `obs/utils.py` come through.

    The `"SHIP"` fallback in `obs/utils.py` is still deliberately NOT accepted here. On the Add
    Spare path it is harmless and is left exactly as it is. On the import path it is not: it
    would put the literal string `SHIP` at the front of every generated pattern number and leave
    the workbook's own mandatory column with nothing to be reconciled against.
    """
    code = _resolve_adopted_ship_customer_code()
    if not code:
        raise PatternSourceUnavailable(NO_SHIP_MESSAGE)
    return code


def import_adopted_customer_code():
    """Developed by Unknown: the adopted MO customer code, or "" - the non-raising sibling.

    `import_ship_customer_code` raises, which is right where a caller cannot continue without a
    code. The import gate CAN continue without one - that is the first import, and it adopts.
    So it needs to ask the question without being refused for asking.
    """
    return _resolve_adopted_ship_customer_code()


def _resolve_adopted_ship_customer_code():
    """STUB (merge decision, blocker #2): source's `rbac.resolve_ship_customer_code()` reads a
    persisted `ShipIdentity.customer_code`, which does not exist anywhere in target's `accounts`
    app and is deliberately not being added there in this pass (that would be an out-of-scope
    change to a different app). Rather than crash on a missing attribute, this is a safe no-op
    that always reports "nothing adopted yet" - every import is therefore treated as the
    first-ever import (see `import_ship_customer_code`'s docstring: the sheet's own code is then
    taken as authoritative for that request, so long as the sheet agrees with itself). No MO
    customer code is ever persisted across requests until `accounts` grows real support for it.
    """
    return ""


def sheet_customer_codes(raw_rows):
    """Developed by Unknown: the distinct non-empty SHIP CUSTOMER CODE values a sheet carries,
    in first-seen order.

    Built on `sheet_customer_code_of` so there is one reader of that cell. Order is kept because
    the first-seen code is the one a first import adopts, and the one the disagreement message
    names as the sheet's own.
    """
    seen = []
    for _row_number, row in raw_rows:
        code = sheet_customer_code_of(row)
        if code and code not in seen:
            seen.append(code)
    return seen


def sheet_disagrees_message(codes, mismatched, limit=20):
    """Developed by Unknown: the refusal for a FIRST import whose own rows disagree.

    Nothing is adopted from a sheet that contradicts itself - picking one of two codes would
    silently settle the ship's identity on a coin toss. Names the first-seen code, then the rows
    that differ from it, capped the same way the mismatch message is.
    """
    listed = mismatched[:limit]
    detail = ", ".join(f"row {number} holds {held}" for number, held in listed)
    if len(mismatched) > limit:
        detail = f"{detail}, and {len(mismatched) - limit} further row(s)"
    return (
        f"This workbook does not agree with itself on the MO customer code, so no code has "
        f"been adopted and nothing has been loaded. The first row holds {codes[0]} and "
        f"{len(mismatched)} row(s) hold a different code - {detail}. The MO customer code must "
        f"be the same in every row. Correct the SHIP CUSTOMER CODE column and import again."
    )
