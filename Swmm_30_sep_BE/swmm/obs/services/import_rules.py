def apply_working_table_edits(raw_rows, edits, removed_rows):
    """Overlay the client's working-table corrections onto the parsed sheet.

    `raw_rows` is `_parse_excel_workbook`'s `[(row_number, {sheet_key: cell}), ...]`.
    `edits` is `{row_number: {display_field: cell_value}}` and `removed_rows` is a set of
    row numbers the user deleted from the working table. Returns a NEW list - the parsed
    rows are copied rather than mutated, so a caller still holds the workbook as it was
    read.

    An edit naming a row the sheet does not carry is ignored rather than reported: the only
    way to reach that state is a file swapped between two calls, which the screen's own
    stale-preview guard already forces a fresh preview for. Every value is written as text,
    exactly as a workbook cell would have held it, so the same `_clean_import_*` helpers and
    the same rule engine read an edited cell and a typed one identically.
    """
    if not edits and not removed_rows:
        return raw_rows

    overlaid = []
    for row_number, row in raw_rows:
        if row_number in removed_rows:
            continue
        row_edits = edits.get(row_number)
        if not row_edits:
            overlaid.append((row_number, row))
            continue
        corrected = dict(row)
        for field, value in row_edits.items():
            corrected[IMPORT_EDIT_FIELD_TO_SHEET_KEY[field]] = value
        overlaid.append((row_number, corrected))
    return overlaid


# Developed by Unknown: Hand entry, and why it produces a SHEET ROW rather than a payload.
#
# Requirement 3.3 gives the page two entry modes - a template workbook, and rows built by hand
# in the working table. There is exactly ONE rule engine and it reads the normalised
# `{sheet_key: cell}` dictionary `ExcelImportExportMixin._parse_excel_workbook` produces. A
# hand-built row is therefore turned into that same dictionary here, and from that point on it
# is indistinguishable from a row read out of a workbook - the same source-of-truth
# cross-check, the same `validate_import_row`, the same serializer and the same
# `Spares.full_clean()` run over it, in the same order, on the same endpoints. Nothing about
# the rule engine changes and no rule is implemented a second time.
#
# Two columns have no control on the hand-entry form and are supplied here rather than typed:
#
#   AUTHORITY           the operator picks ONE import authority for the batch, exactly as they
#                       do for a workbook, and every row carries it. It is a whole-file gate
#                       and never a per-row value - the same reason `authority` is absent from
#                       `IMPORT_EDIT_FIELD_TO_SHEET_KEY` above.
#   SHIP CUSTOMER CODE  unique to the ship and reconciled against the active ship's own code.
#                       There is no sheet to type it into, so the ship's own code is written
#                       into every row and clauses 2.23.1 and 2.23.2 are then satisfied by
#                       construction rather than by exemption - the checks still run.
#
# Every other sheet key is defaulted to the empty string, so a column the operator left alone
# reads exactly as an empty workbook cell reads and fails, or does not fail, on its own clause.
def manual_row_to_sheet_row(values, *, authority, ship_customer_code):
    """Turn one hand-built row into the `{sheet_key: cell}` dictionary the rule engine reads.

    `values` is keyed by the display field names `IMPORT_EDIT_FIELD_TO_SHEET_KEY` carries -
    the same seventeen names an `edits` entry uses - so the hand-entry form and the working
    table's Edit dialogue speak one vocabulary.
    """
    row = dict.fromkeys(IMPORT_EDIT_FIELD_TO_SHEET_KEY.values(), "")
    for field, value in values.items():
        row[IMPORT_EDIT_FIELD_TO_SHEET_KEY[field]] = value
    row["authority_name"] = authority
    row["ship_customer_code"] = ship_customer_code
    return row


