def authority_mismatch_rows(raw_rows, selected_authority):
    """Every row whose AUTHORITY cell disagrees with the authority the user selected.

    Returns a list of `(row_number, what_the_cell_holds)`. The caller refuses the WHOLE file
    on a non-empty result - decision A-02 makes this one rule a file-level gate rather than
    a per-row flag, because an authority mismatch means the operator picked the wrong sheet
    or the wrong authority, and letting the agreeing rows through would load half a sheet
    under an authority its own workbook does not claim.
    """
    expected = (selected_authority or "").strip().upper()
    mismatched = []
    for row_number, row in raw_rows:
        held = cell_text(row.get("authority_name")).strip().upper()
        if held != expected:
            mismatched.append((row_number, held))
    return mismatched


def authority_mismatch_message(selected_authority, mismatched, limit=20):
    """The refusal sentence, naming the offending rows and what each of them holds."""
    listed = mismatched[:limit]
    parts = [
        f"row {row_number} holds {held or 'nothing'}" for row_number, held in listed
    ]
    detail = ", ".join(parts)
    if len(mismatched) > limit:
        detail = f"{detail}, and {len(mismatched) - limit} further row(s)"
    return (
        f"Rule 2.17 - the whole file is refused. Every row's AUTHORITY must read "
        f"{selected_authority} on this import, and {len(mismatched)} row(s) do not - "
        f"{detail}. Nothing has been loaded. Correct the workbook, or choose the import "
        f"authority the sheet actually carries, and import again."
    )


def _whole_number(text):
    """Return the cell as a non-negative int, or `None` when it is not a whole number.

    An empty cell also returns `None` - the caller distinguishes the two, because rules
    2.11.1 and 2.12.3 make an empty cell a failure in its own right and the workbook's
    own error string already covers both cases in one sentence.
    """
    candidate = text.strip()
    if not candidate:
        return None
    try:
        number = float(candidate)
    except (TypeError, ValueError):
        return None
    if not number.is_integer():
        return None
    return int(number)


def _check_general_rules(row, errors):
    """Rules 2.1, 2.3 and 2.4, applied to every mapped text cell of the row.

    These are REJECTIONS, not corrections. The serializer and model mixins that
    upper-case and strip a value on the Add Spare path are left exactly as they are, and
    on the import path they now never see a value that needed either - which is the point.
    A ship's staff member who typed a value in lower case is told so and corrects the
    workbook, rather than having the sheet quietly rewritten under them.
    """
    for field in GENERAL_RULE_FIELDS:
        text = cell_text(row.get(field))
        if not text:
            continue
        if any(char.isalpha() for char in text) and not text.isupper():
            errors.setdefault(field, []).append(RULE_MESSAGES["R-001"])
        if "  " in text.strip():
            errors.setdefault(field, []).append(RULE_MESSAGES["R-004"])
        if text != text.strip():
            errors.setdefault(field, []).append(RULE_MESSAGES["R-005"])


# Developed by Unknown: THE MASTER LOOKUP CACHE. `_check_spare_class`, `_check_equipment_class`,
# `_check_denomination` and `_check_authority` each used to run one fresh `.filter(...).first()`
# per ROW - four extra queries per row, against tables that hold one department's whole master
# list and do not change mid-import. A 500-row sheet cost 2,000 round trips finding out things
# the first row's queries had already answered.
#
# `build_master_lookup_cache` runs those same four lookups ONCE, for the WHOLE department, and
# the four checkers below consult the resulting dict instead when a cache is given. `cache=None`
# (the default on every checker) keeps the original per-call query, so a caller that validates a
# single row in isolation - the Add Spare path, a test, anything outside the sheet import loop -
# is completely unaffected. Only `validate_import_row`'s sheet-import callers build and pass one.
#
# Keyed on `name.upper()`, matching every call site's own `.strip().upper()` on the cell text -
# an `__iexact` lookup and a Python dict keyed on the upper-cased name answer the same question.
MasterLookupCache = namedtuple(
    "MasterLookupCache",
    ["spare_classes", "equipment_classes", "denominations", "authorities"],
)


def build_master_lookup_cache(department):
    """One query per master table, for the WHOLE department, instead of one per row per table.

    Returns a `MasterLookupCache`. Safe to build once per import and pass to every
    `validate_import_row` call for that sheet - none of the four tables it reads can change
    mid-import, since nothing on this read-only preview/commit-valid path writes to them.
    """
    if department is None:
        return MasterLookupCache({}, {}, {}, {})
    return MasterLookupCache(
        spare_classes={
            spare_class.name.upper(): spare_class
            for spare_class in SpareClass.objects.filter(department=department)
        },
        equipment_classes={
            equipment_class.name.upper(): equipment_class
            for equipment_class in EquipmentClass.objects.filter(
                spare_class__department=department
            )
        },
        denominations={
            denomination.name.upper(): denomination
            for denomination in Denomination.objects.filter(department=department)
        },
        # Developed by Unknown: NOT department-scoped, matching `_check_authority`'s own
        # `Authority.objects.filter(name__iexact=text)` below, which carries no department
        # filter either - `Authority` is a ship-wide table, not a per-department one.
        authorities={
            authority.name.upper(): authority for authority in Authority.objects.all()
        },
    )


def _check_spare_class(row, errors, department, route, cache=None):
    """Rules 2.5 and 2.5.3, plus the master-list check that replaces row-time creation."""
    text = cell_text(row.get("spare_class_name")).strip().upper()
    if not text:
        errors.setdefault("spare_class_name", []).append(RULE_MESSAGES["R-011"])
        return None
    department_name = getattr(department, "name", "")
    if text not in permitted_spare_classes(department_name, route):
        errors.setdefault("spare_class_name", []).append(RULE_MESSAGES["R-010"])
        return None
    if cache is not None:
        spare_class = cache.spare_classes.get(text)
    else:
        spare_class = SpareClass.objects.filter(
            name__iexact=text, department=department
        ).first()
    if spare_class is None:
        errors.setdefault("spare_class_name", []).append(RULE_MESSAGES["R-010-MASTER"])
    return spare_class


def _check_equipment_class(row, errors, spare_class_text, spare_class, pending, cache=None):
    """Rules 2.6.2, 2.6.3 and 2.6.4, plus the master-list check.

    Clause 2.6's own requirement - that the text match the equipment name entry in the
    D787J document exactly - cannot be checked against the document, which is a paper
    holding of the ship. Requiring the name to already exist as an `EquipmentClass` in
    the row's DEPARTMENT is the enforceable form of it, and it is what stops the import
    from minting an equipment class out of a typing slip.

    Developed by Unknown: the master lookup is scoped to the department, not to the row's
    spare class. `EquipmentClass` is unique per department - one name, one row, whichever
    spare class it hangs off - and the lookup has to match that or the two disagree. It
    used to filter on `spare_class`, which made the shipped workbooks unimportable: rules
    2.6.2 and 2.6.3 give MICELLANEOUS to SPARES_PLL, SPARES_MICELLANEOUS and
    SPARES_CONSUMABLE alike, so the Engineering OTHERS workbook names it under three spare
    classes, and only one of the three could ever resolve.

    Nothing is loosened by this. Which equipment class a spare class may name is rules
    2.6.2 and 2.6.3, and they are enforced immediately above by
    `EQUIPMENT_CLASS_BY_SPARE_CLASS` - a SPARES_PLL row naming AIR CONDITIONING PLANT
    still fails R-013, department-wide lookup or not.
    """
    text = cell_text(row.get("equipment_class_name")).strip().upper()
    if not text:
        errors.setdefault("equipment_class_name", []).append(RULE_MESSAGES["R-015"])
        return None

    fixed = EQUIPMENT_CLASS_BY_SPARE_CLASS.get(spare_class_text)
    if fixed is not None and text not in fixed:
        message = (
            RULE_MESSAGES["R-014"]
            if spare_class_text == "SPARES_CONSUMABLE"
            else RULE_MESSAGES["R-013"]
        )
        errors.setdefault("equipment_class_name", []).append(message)
        return None

    if spare_class is None:
        return None
    # Developed by Unknown: an equipment name this sheet introduces is added without anyone
    # being asked - clause 2.6.1 already permits any name the ship's D787J document carries, and
    # the template workbook's own dropdown offers `OTHER - ENTER EQUIPMENT NAME AS IN D787J` for
    # exactly this. The two closed lists above still apply and have already run.
    if text in pending.equipment_classes:
        return None
    if cache is not None:
        equipment_class = cache.equipment_classes.get(text)
    else:
        equipment_class = EquipmentClass.objects.filter(
            name__iexact=text, spare_class__department=spare_class.department
        ).first()
    if equipment_class is None:
        errors.setdefault("equipment_class_name", []).append(
            RULE_MESSAGES["R-012-MASTER"]
        )
    return equipment_class


def _check_denomination(row, errors, department, pending, cache=None):
    """Rules 2.10.1 and 2.10.2, plus the master-list check.

    Developed by Unknown: `pending` is the set of denominations THIS SHEET introduces and that
    are on offer to be added. A value in it is neither of the two failures below - it is not a
    breach of clause 2.10.1 and it is not a missing master row. It is a new unit the Head of
    Department has been asked about, so no message is written and the row is marked as awaiting
    that answer by the caller.
    """
    text = cell_text(row.get("denomination_name")).strip().upper()
    if not text:
        errors.setdefault("denomination_name", []).append(RULE_MESSAGES["R-025"])
        return None
    if text in pending.denominations:
        return None

    # Developed by Unknown: THE MASTER LIST IS CONSULTED FIRST, AND THAT ORDER IS THE WHOLE OF
    # THE RULE.
    #
    # It used to be the other way round - clause 2.10.1's five names were checked first and a
    # sixth was refused with R-024 before the department's own register was ever read. That was
    # right while the register could only ever hold those five. It is wrong now that a Head of
    # Department can deliberately add one, because it refused the value on the very next import
    # after approving it: the row was added to `obs_denomination`, and the constant list then
    # threw it out anyway. Adding a denomination would have meant nothing at all.
    #
    # A row in the department's register is a value the ship has DECIDED it holds, so it passes.
    # The document's list remains the default and remains what a ship gets seeded with; it is
    # the answer for a value nobody has decided anything about.
    if cache is not None:
        denomination = cache.denominations.get(text)
    else:
        denomination = Denomination.objects.filter(
            name__iexact=text, department=department
        ).first()
    if denomination is not None:
        return denomination

    # Not held. Which message depends on whether the document names it: one the document lists
    # is a seeding gap on this deployment, and one it does not list is a value nobody has
    # approved.
    message = "R-024-MASTER" if text in DENOMINATIONS else "R-024"
    errors.setdefault("denomination_name", []).append(RULE_MESSAGES[message])
    return None


def _check_authority(row, errors, department, route, pending, cache=None):
    """Rules 2.17.1, 2.17.2 and 2.17.3, plus the master-list check.

    Developed by Unknown: The permitted set is now the SELECTED route's, so rule 2.17.1 -
    "on the D787J route the column must read D787J only" - is enforced here for the first
    time. The file-level gate the endpoint applies first means a mismatch normally never
    reaches this check, but the rule stays where the register says it lives so it is still
    enforced on any path that does not run the file gate.
    """
    text = cell_text(row.get("authority_name")).strip().upper()
    if not text:
        errors.setdefault("authority_name", []).append(RULE_MESSAGES["R-040"])
        return None
    # Developed by Unknown: as for the denomination above - a value this sheet introduces on the
    # OTHERS route is awaiting an answer, not failing a rule. `collect_master_additions` never
    # offers one on the D787J route, so clause 2.17.1 is untouched by this line.
    if text in pending.authorities:
        return None

    if cache is not None:
        authority = cache.authorities.get(text)
    else:
        authority = Authority.objects.filter(name__iexact=text).first()

    # Developed by Unknown: An authority the ship has added to its own register passes, for the
    # same reason a denomination does - approving one and then refusing it on the next import
    # would make the approval meaningless. TWO NARROWINGS, and neither is negotiable:
    #
    #   THE D787J ROUTE IS UNTOUCHED. Clause 2.17.1 says that when the D787J radio button is
    #   selected "the column text must read D787J only". That is not a list a ship may extend,
    #   it is a statement about what a D787J import IS, so the route check below runs first and
    #   an added authority never reaches it.
    #
    #   `D787J` ITSELF IS NEVER ACCEPTED ON THE OTHERS ROUTE. It has a master row on every
    #   seeded ship - `AUTHORITIES` includes it - so a bare "does it exist" test would have let
    #   an OTHERS sheet claim D787J authority for its rows. Clause 2.17.2's list is the seven,
    #   and D787J is not one of them.
    added_by_the_ship = (
        authority is not None
        and route == IMPORT_ROUTE_OTHERS
        and text != AUTHORITY_D787J
    )
    if not added_by_the_ship and text not in permitted_authorities(
        getattr(department, "name", ""), route
    ):
        message = (
            RULE_MESSAGES["R-038"]
            if route == IMPORT_ROUTE_D787J
            else RULE_MESSAGES["R-039"]
        )
        errors.setdefault("authority_name", []).append(message)
        return None
    if authority is None:
        errors.setdefault("authority_name", []).append(RULE_MESSAGES["R-039-MASTER"])
    return authority


def _check_quantities(row, errors, route):
    """Rules 2.11.1, 2.11.2, 2.11.3, 2.11.4 and 2.12.3.

    The third part of the quantity rule - held may never exceed authorised, on any route -
    is NOT repeated here. `Spares.clean()` already carries it and is already reached
    through `full_clean()` on the import path, so it stays the single place that rule
    lives. A shortfall on the D787J route is permitted by clause 2.12.1 and is not an
    error at all.
    """
    authorised = _whole_number(cell_text(row.get("quantity_authorised")))
    available = _whole_number(cell_text(row.get("quantity_available")))
    if authorised is None or authorised < 1:
        errors.setdefault("quantity_authorised", []).append(RULE_MESSAGES["R-026"])
    if available is None:
        errors.setdefault("quantity_available", []).append(RULE_MESSAGES["R-032"])
    if (
        authorised is not None
        and available is not None
        and route == IMPORT_ROUTE_OTHERS
        and authorised != available
    ):
        errors.setdefault("quantity_authorised", []).append(RULE_MESSAGES["R-028"])


def _check_remaining_columns(row, errors, route):
    """The per-cell rules that need no master-data lookup and no cross-column context.

    COMPARTMENT NAME, RACK NUMBER and BOX NUMBER carry no rule here on purpose. Clauses
    2.13 to 2.16 state no "cannot be empty" for any of them and the rules document marks
    none of them with its mandatory asterisk, so an empty cell is permitted and keeps the
    model default. RACK POSITION is optional in the same way, but a value that IS typed
    must be one of the three.

    Developed by Unknown: `route` is now the SELECTED import route, not one inferred from
    the row's own authority cell, so rules 2.18 and 2.19 make the D787J page and line
    mandatory on every row of a D787J import - including a row whose authority cell was
    left blank, which the inferred version would have treated as an others-route row and
    let through.
    """
    pattern_number = cell_text(row.get("pattern_number")).strip()
    if any(symbol in pattern_number for symbol in PATTERN_NUMBER_FORBIDDEN_SYMBOLS):
        errors.setdefault("pattern_number", []).append(RULE_MESSAGES["R-019"])

    if not cell_text(row.get("description")).strip():
        errors.setdefault("description", []).append(RULE_MESSAGES["R-020"])

    # Developed by Unknown: The membership test is on the value NORMALISED through
    # `source_category`, not on the raw cell, and that is a fix rather than a loosening.
    #
    # The rule engine runs over the row AFTER `apply_source_of_truth` has corrected it, and that
    # correction writes `Spares.category`'s full WORD. So a row whose source of truth disagreed
    # with the sheet arrived here holding `CONSUMABLE`, `CONSUMABLE` is not in a tuple of
    # letters, and the row failed "only P, C or R" on a value the application itself had just
    # written - with nothing the operator could do about it, because the source is the authority
    # and the workbook cell is what got overwritten. `apply_source_of_truth` already guards
    # against exactly this for DESCRIPTION, collapsing the source's whitespace so rules 2.3 and
    # 2.4 pass on its own output; CATEGORY had no equivalent.
    #
    # Normalising here rather than at the point of correction covers every path that can put a
    # word in this cell, not just that one.
    category = cell_text(row.get("category")).strip().upper()
    if not category:
        errors.setdefault("category", []).append(RULE_MESSAGES["R-023"])
    elif source_category(category) not in PERMITTED_CATEGORIES:
        errors.setdefault("category", []).append(RULE_MESSAGES["R-021"])

    rack_position = cell_text(row.get("rack_position")).strip().upper()
    if rack_position and rack_position not in RACK_POSITIONS:
        errors.setdefault("rack_position", []).append(RULE_MESSAGES["R-035"])

    critical = cell_text(row.get("critical")).strip().upper()
    if critical and critical not in CRITICAL_VALUES:
        errors.setdefault("critical", []).append(RULE_MESSAGES["R-043"])

    if route == IMPORT_ROUTE_D787J:
        if not cell_text(row.get("page")).strip():
            errors.setdefault("page", []).append(RULE_MESSAGES["R-041"])
        if not cell_text(row.get("line")).strip():
            errors.setdefault("line", []).append(RULE_MESSAGES["R-042"])


def _check_ship_customer_code(row, errors, sheet_customer_code):
    """Rules 2.23.1 and 2.23.2.

    Returns the code this row carries, so the caller can hold the sheet's first non-empty
    one and compare every later row against it - which is the whole of clause 2.23.1's
    "the same value must be entered in every row".
    """
    text = cell_text(row.get("ship_customer_code")).strip().upper()
    if not text:
        errors.setdefault("ship_customer_code", []).append(RULE_MESSAGES["R-046"])
        return None
    if sheet_customer_code is not None and text != sheet_customer_code:
        errors.setdefault("ship_customer_code", []).append(RULE_MESSAGES["R-006"])
    return text


def validate_import_row(
    row, *, department, route, sheet_customer_code=None, pending=None, masters_cache=None
):
    """Apply the import rule register to one workbook row, on one selected import route.

    `row` is the normalised `{target: cell value}` dictionary
    `ExcelImportExportMixin._parse_excel_workbook` produces - raw cell values, not cleaned
    ones, which is what rules 2.1, 2.3 and 2.4 need to see.

    `route` is the route the CALLER selected, one of `IMPORT_ROUTES`. It is a required
    argument rather than an inferred one - every rule that reads "during a D787J import"
    means the radio button, not the cell.

    Returns an `ImportRowRules`. `errors` is empty for a row that breaches no clause, and
    that row then goes on to the serializer and to `Spares.full_clean()` as before - this
    engine adds rules, it does not replace the ones already there.
    """
    errors = {}
    if department is None:
        return ImportRowRules(
            {"spare_class_name": [RULE_MESSAGES["NO-DEPARTMENT"]]}, EMPTY_MASTERS
        )

    pending = pending or NO_PENDING_MASTERS
    spare_class_text = cell_text(row.get("spare_class_name")).strip().upper()

    _check_general_rules(row, errors)
    spare_class = _check_spare_class(row, errors, department, route, cache=masters_cache)
    equipment_class = _check_equipment_class(
        row, errors, spare_class_text, spare_class, pending, cache=masters_cache
    )
    denomination = _check_denomination(row, errors, department, pending, cache=masters_cache)
    authority = _check_authority(
        row, errors, department, route, pending, cache=masters_cache
    )
    _check_quantities(row, errors, route)
    _check_remaining_columns(row, errors, route)
    _check_ship_customer_code(row, errors, sheet_customer_code)

    return ImportRowRules(
        errors,
        ImportRowMasters(spare_class, equipment_class, denomination, authority),
    )


# Developed by Unknown: THE IMPORT ROW-CLEANING AND MASTER-RESOLUTION HELPERS, moved off
# `SparesViewSet` during the obs file-structure split's optimization 2.3.
#
# These were `@staticmethod`s on `SparesViewSet` with no dependency on `self` or `request` -
# pure functions of a cell value (and, for the four `_resolve_*` lookups, a parent master
# row) - so they belong beside the rule engine they support rather than on the viewset.
# `views/spares_import.py`'s `SparesImportMixin` calls these directly now.
#
# Developed by Unknown: These four `_resolve_*` were `_get_or_create_*` and each one CREATED
# the master row on a miss - a mis-typed spare class became a new SpareClass, an
# unrecognised `PCS` became a new Denomination, and a workbook cell reading `SHIP STAFF`
# became a new Authority in the shared master table, permanently. That is the single largest
# reason a sheet full of deliberate breaches reported almost every row valid. They now look
# up only, and a miss is a row failure carrying the clause-led message the rule engine
# writes. Nothing else called them - they were reachable from `build_excel_import_payload`
# alone - so the single-spare Add Spare path is untouched by this change, as is
# `submit_validated_inventory_data`, which has its own `get_or_create` calls and belongs to a
# later change.
def _clean_import_text(value, default=""):
    if value in (None, ""):
        return default
    if isinstance(value, float) and value.is_integer():
        return str(int(value)).strip()
    return str(value).strip()


# Developed by Unknown: Was `return 0` for an empty cell, a non-numeric cell and a
# negative one alike, and `int(float(value))` silently truncated `2.5` to `2`. Rules
# 2.11.2 and 2.12.3 make each of those a row failure, so nothing may be manufactured
# here. `None` is returned instead, which the serializer rejects rather than stores.
# The clause-led message a ship's staff member actually reads comes from the rule
# engine - this only stops the bad value reaching the database if the engine is
# bypassed, as it is on the strict `import_excel` path.
def _clean_import_int(value):
    if value in (None, ""):
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    if not number.is_integer() or number < 0:
        return None
    return int(number)


def _clean_import_bool(value):
    if isinstance(value, bool):
        return value
    return str(value or "").strip().upper() in {"1", "TRUE", "YES", "Y"}


# Developed by Unknown: The unrecognised-value fallback was `Spares.PERMANENT`, so a
# CATEGORY of `X` was stored as PERMANENT and the row imported silently wrong. It returns
# "" instead, which the serializer's choice field rejects.
#
# THE MAP IT USED TO CARRY IS GONE, and it delegates to `source_category` instead. There
# were two copies of one mapping and they had drifted: this one knew six spellings,
# `CATEGORY_BY_SOURCE_CODE` (`pattern.py`) knows ten, and the four it did not know were
# every spelling of QUASI-PERMANENT. So a row the import itself corrected to
# `QUASI_PERMANENT` from a WED source - the one category the WED item master's own column
# header names, at `Item Category(C/P/QP)` - arrived here, matched nothing, and was
# blanked. The payload then carried "" and the serializer refused the row. One map, one
# place, and the QP a source of truth hands us survives to the database.
def _clean_import_category(value):
    return source_category(value) or ""


# Developed by Unknown: THE OTHER DIRECTION, and the reason the CATEGORY column came up
# EMPTY ON EVERY ROW of the working table.
#
# Clause 2.9.1's column carries a LETTER and `Spares.category` stores the FULL WORD. The
# display builder reused `_clean_import_category` above, so the value it put on the wire was
# always the word - `PERMANENT`, never `P`. The screen's dropdown is built from
# `CATEGORY_CODES` and its option values are the LETTERS, so nothing ever matched and every
# cell rendered blank, whatever the sheet said.
#
# The working table shows the workbook's own columns under the workbook's own names, so it
# shows the workbook's own values too: the letter goes to the screen and the word goes to the
# database, and this is the one place the first direction is taken.
def _display_import_category(value):
    return CATEGORY_LETTER_BY_WORD.get(source_category(value), "")


def _resolve_authority(name):
    clean_name = _clean_import_text(name).upper()
    if not clean_name:
        return None
    return Authority.objects.filter(name__iexact=clean_name).first()


def _resolve_spare_class(name, department):
    clean_name = _clean_import_text(name).upper()
    if not clean_name:
        return None
    return SpareClass.objects.filter(
        name__iexact=clean_name,
        department=department,
    ).first()


def _resolve_equipment_class(name, spare_class):
    clean_name = _clean_import_text(name).upper()
    if not clean_name or spare_class is None:
        return None
    return EquipmentClass.objects.filter(
        name__iexact=clean_name,
        spare_class=spare_class,
    ).first()


def _resolve_denomination(name, department):
    clean_name = _clean_import_text(name).upper()
    if not clean_name:
        return None
    return Denomination.objects.filter(
        name__iexact=clean_name,
        department=department,
    ).first()


