# Developed by Unknown: WHICH DEPARTMENTS HOLD A D787J AT ALL. This is the single source of
# truth for that question, and every other place that used to decide it now reads these.
#
# Rules document clause 2.5.1 states it exactly: "For import of D787J Spares of Engg. Elec
# and Hull Dept". Nothing else on the ship holds a D787J document, so nothing else may import
# on that route.
#
# An earlier build exceeded this. D787J spare-class rows had been transcribed for EXECUTIVE
# and MEDICAL, and LOGISTICS had no row at all so it fell through to the widest list of all -
# three departments that clause 2.5.1 does not name. All three of their D787J workbooks were
# generated by INFERENCE and say so in their own GUIDANCE sheet ("THE RULES DOCUMENT STATES
# NO PERMITTED SPARE CLASSES FOR THIS DEPARTMENT"). The set of inferred workbooks and the set
# of over-broad departments were exactly the same three, which is what settled it.
#
# HULL is named by clause 2.5.1 and appears in the schema TWICE, which is why it is listed
# twice below. `rbac.HIDDEN_DEPARTMENTS` retires it from the department picker and the ship
# holds it as an EXECUTIVE sub-department under a Dy HOD, but a `Department` row named HULL
# still exists and is what the shipped `HULL_..._D787.xlsx` workbook imports against. Naming
# it in both places means the same hull scope is recognised whichever way a deployment models
# it, and the Executive branch - which holds no D787J of its own - reaches the route ONLY by
# selecting HULL in the Sub Department field. That last case is why this question cannot be
# answered from a department name alone.
D787J_DEPARTMENTS = frozenset({"ENGINEERING", "ELECTRICAL", "HULL"})
D787J_SUB_DEPARTMENTS = {"EXECUTIVE": frozenset({"HULL"})}


def department_has_d787j(department_name, sub_department_name=""):
    """Developed by Unknown: True when this scope holds a D787J document.

    `sub_department_name` matters only for EXECUTIVE, where the branch itself holds no D787J
    but its HULL sub-department does. Both the Hull Dy HOD, who is confined to HULL, and the
    Executive Head of Department choosing HULL in the Sub Department field reach it this way -
    they arrive with the same pair of values, so one test serves both.

    Developed by Unknown: the name is put through `canonical_department_name` first, because
    the caller hands over whatever `Master_department.name` holds and that is not always the
    canonical word. A CMMS-synced deployment can name the Engineering row `E`, which matched
    nothing here and silently withdrew the D787J route from the one department clause 2.5.1
    names first. Resolving it is the same rule, asked of a row that spells itself differently.
    """
    department = canonical_department_name(department_name)
    if department in D787J_DEPARTMENTS:
        return True
    permitted = D787J_SUB_DEPARTMENTS.get(department)
    if not permitted:
        return False
    return (sub_department_name or "").strip().upper() in permitted


def permitted_routes(department_name, sub_department_name=""):
    """Developed by Unknown: the import routes open to this scope, in offer order.

    Every department can import on OTHERS. Only those holding a D787J can import on D787J.
    """
    if department_has_d787j(department_name, sub_department_name):
        return (IMPORT_ROUTE_D787J, IMPORT_ROUTE_OTHERS)
    return (IMPORT_ROUTE_OTHERS,)


