def cell_text(value):
    """Return a workbook cell as text WITHOUT stripping it.

    Rules 2.3 and 2.4 are about the spaces themselves, so the raw spacing has to survive
    as far as the check. openpyxl hands a whole number back as a float, which would
    otherwise read as `3.0`, so an integral float is narrowed first.
    """
    if value is None:
        return ""
    if isinstance(value, bool):
        return "YES" if value else ""
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def permitted_spare_classes(department_name, route):
    """The SPARE CLASS values clause 2.5 permits for one department on one route.

    Resolved through `canonical_department_name` for the reason `department_has_d787j`
    records - a department row named `E` missed this map entirely and fell through to the
    widest list of all, which is the one answer clause 2.5 never gives.
    """
    by_route = SPARE_CLASS_BY_DEPARTMENT_AND_ROUTE.get(
        canonical_department_name(department_name)
    )
    if by_route is None:
        return SPARE_CLASS_BY_ROUTE[route]
    return by_route[route]


def authority_options(department_name, route, sub_department_name=""):
    """The AUTHORITY values clauses 2.17.1 and 2.17.2 permit, in the order they are offered.

    A list, not a set, because the order is carried across from the reference application's
    own dropdown and a screen has to render it. The department restriction narrows the
    route's list and never widens it - an empty list means the department has no such route
    at all, which is true of NBCD on D787J.

    Developed by Unknown: `sub_department_name` was added because the D787J question cannot be
    answered from a department name alone. EXECUTIVE holds no D787J, but its HULL
    sub-department does, so the same department name gives two different answers depending on
    which sub-department the rows are being imported for.
    """
    by_route = AUTHORITY_OPTIONS_BY_ROUTE[route]
    # Developed by Unknown: the D787J route is withdrawn entirely from a scope that holds no
    # D787J document. Checked before `AUTHORITY_BY_DEPARTMENT`, which is a different and
    # narrower rule - NBCD is restricted to CNAL on the route it DOES have.
    if route == IMPORT_ROUTE_D787J and not department_has_d787j(
        department_name, sub_department_name
    ):
        return []
    allowed = AUTHORITY_BY_DEPARTMENT.get(canonical_department_name(department_name))
    if allowed is None:
        return list(by_route)
    return [name for name in by_route if name in allowed]


def permitted_authorities(department_name, route, sub_department_name=""):
    """Set form of `authority_options`, for a membership test."""
    return frozenset(authority_options(department_name, route, sub_department_name))


