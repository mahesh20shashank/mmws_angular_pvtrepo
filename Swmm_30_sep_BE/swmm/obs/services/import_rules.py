# clause 2.10.1's five. A `NOS` whose master row has merely not been seeded on this deployment
# is not a departure from the document and nobody is asked to approve it.
PendingMasters = namedtuple(
    "PendingMasters",
    ["denominations", "authorities", "equipment_classes", "needs_confirmation"],
)

NO_PENDING_MASTERS = PendingMasters(
    frozenset(), frozenset(), frozenset(), frozenset()
)

