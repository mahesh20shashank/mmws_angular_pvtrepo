def master_addition_key(field, value):
    """The identity of one addition, used to match a client's confirmation to a collected one.

    Upper-cased on both sides, because every value on this path is upper-cased by clause 2.1
    and a confirmation that failed to match on case alone would silently skip the row.
    """
    return (field or "").strip(), (value or "").strip().upper()


def _rules_list_for(field, department, route):
    """The values the rules document itself permits in this column, for this scope.

    Developed by Unknown: the EQUIPMENT CLASS arm used to return the department's seeded list,
    which no longer exists - clause 2.6.1 permits any name the ship's own D787J document carries,
    so there is no list of permitted equipment names for a ship and never honestly was one. What
    the document DOES name is the closed set at clauses 2.6.2 and 2.6.3, so that is what is
    returned; every other name reads as `in_rules=False`, which is exactly what it is.

    Nothing changes for the operator either way: `collect_master_additions` forces
    `confirmation_required=False` for every equipment class, so `in_rules` is reported and never
    gates anything on this column.
    """
    if field == "denomination_name":
        return DENOMINATIONS
    if field == "authority_name":
        return permitted_authorities(getattr(department, "name", ""), route)
    return frozenset(
        name for names in EQUIPMENT_CLASS_BY_SPARE_CLASS.values() for name in names
    )


def _master_row_exists(field, value, department):
    """Whether this column's master table already holds the value for this department."""
    if field == "denomination_name":
        return Denomination.objects.filter(
            name__iexact=value, department=department
        ).exists()
    if field == "authority_name":
        return Authority.objects.filter(name__iexact=value).exists()
    return EquipmentClass.objects.filter(
        name__iexact=value, spare_class__department=department
    ).exists()


def collect_master_additions(raw_rows, department, route):
    """Every master value this sheet introduces, deduplicated, in first-seen order.

    A PURE READ. Nothing here writes, which is what lets the preview and the commit call it
    with the same arguments and get the same answer - the preview reports the list, the commit
    creates the confirmed part of it.

    A value already in its master table is not an addition and is absent from the result. So is
    an empty cell, and so is a whole column when the department could not be resolved.
    """
    if department is None:
        return []

    rows_by_key = {}
    order = []
    # Developed by Unknown: `_master_row_exists` used to be re-queried for every row repeating a
    # value that already exists in masters - `rows_by_key` only ever remembered the OTHER branch
    # (a value this sheet is introducing), so the common case - a value everybody already has -
    # got no caching at all. A 500-row sheet where every denomination/authority/equipment class
    # already exists cost up to 1,500 queries finding that out, once per row instead of once per
    # distinct value. This dict remembers BOTH answers, keyed the same way `rows_by_key` is.
    exists_cache = {}

    for row_number, row in raw_rows:
        for field in MASTER_ADDITION_FIELDS:
            value = cell_text(row.get(field)).strip().upper()
            if not value:
                continue
            # Developed by Unknown: clause 2.17.1 - the D787J route's authority column may read
            # D787J and nothing else, so no authority is addable there. The route is closed, not
            # merely narrow, and an addition would be a way around a rule rather than an
            # extension of a list.
            if field == "authority_name" and route == IMPORT_ROUTE_D787J:
                continue
            key = master_addition_key(field, value)
            if key in rows_by_key:
                rows_by_key[key].append(row_number)
                continue
            exists = exists_cache.get(key)
            if exists is None:
                exists = _master_row_exists(field, value, department)
                exists_cache[key] = exists
            if exists:
                continue
            rows_by_key[key] = [row_number]
            order.append(key)

    additions = []
    for field, value in order:
        column, clause = MASTER_ADDITION_FIELDS[field]
        in_rules = value in _rules_list_for(field, department, route)
        additions.append(
            MasterAddition(
                field=field,
                column=column,
                clause=clause,
                value=value,
                in_rules=in_rules,
                # Developed by Unknown: TWO things skip the question. An EQUIPMENT CLASS never
                # asks it, per clause 2.6.1 above. And a value the rules document DOES name,
                # whose master row simply has not been seeded on this deployment yet, is not a
                # departure from the document at all - asking a Head of Department to approve
                # `NOS` would be asking them to approve clause 2.10.1.
                confirmation_required=(
                    field != "equipment_class_name" and not in_rules
                ),
                rows=tuple(rows_by_key[(field, value)]),
            )
        )
    return additions


def pending_master_values(additions):
    """The three sets `validate_import_row` needs, built from a list of additions."""
    by_field = {field: set() for field in MASTER_ADDITION_FIELDS}
    for addition in additions:
        by_field[addition.field].add(addition.value)
    return PendingMasters(
        denominations=frozenset(by_field["denomination_name"]),
        authorities=frozenset(by_field["authority_name"]),
        equipment_classes=frozenset(by_field["equipment_class_name"]),
        needs_confirmation=frozenset(
            master_addition_key(addition.field, addition.value)
            for addition in additions
            if addition.confirmation_required
        ),
    )


def row_pending_masters(row, pending):
    """The pending additions THIS row is waiting on, as `(field, column, value)` triples.

    The row-level counterpart of `pending_master_values`. The sheet-wide sets say what is on
    offer; this says which of them a particular row actually names, so the working table can
    mark the rows one confirmation would unblock and say which column is waiting.
    """
    if pending is NO_PENDING_MASTERS:
        return ()
    by_field = {
        "denomination_name": pending.denominations,
        "authority_name": pending.authorities,
        "equipment_class_name": pending.equipment_classes,
    }
    waiting = []
    for field, values in by_field.items():
        if not values:
            continue
        value = cell_text(row.get(field)).strip().upper()
        if value and value in values:
            column, _clause = MASTER_ADDITION_FIELDS[field]
            waiting.append(
                RowPendingMaster(
                    field=field,
                    column=column,
                    value=value,
                    confirmation_required=(
                        master_addition_key(field, value) in pending.needs_confirmation
                    ),
                )
            )
    return tuple(waiting)


def unconfirmed_master_additions(additions, confirmed_keys):
    """The additions still waiting on an answer, given what the client actually confirmed.

    An addition that needs no confirmation is never in this list - it is created outright.
    """
    confirmed = {master_addition_key(field, value) for field, value in confirmed_keys}
    return [
        addition
        for addition in additions
        if addition.confirmation_required
        and master_addition_key(addition.field, addition.value) not in confirmed
    ]


def create_master_additions(additions, department):
    """Create the master rows for these additions. Returns the number actually created.

    Callers pass only what may be written - `unconfirmed_master_additions` has already removed
    anything still waiting on an answer. Every write is a `get_or_create`, so a concurrent
    import that got there first costs nothing and a second run of the same sheet creates
    nothing, which is the same contract `seed_equipment_class_defaults` holds itself to.
    """
    created = 0
    for addition in additions:
        if addition.field == "denomination_name":
            _, made = Denomination.objects.get_or_create(
                name=addition.value, department=department
            )
        elif addition.field == "authority_name":
            _, made = Authority.objects.get_or_create(name=addition.value)
        else:
            # Developed by Unknown: an equipment class cannot exist without a spare class to
            # hang off, and the parent is decided by the same function the seed uses so the two
            # can never file the same name differently. A department missing that spare class
            # has not been seeded at all, and the row is skipped rather than inventing one -
            # creating a spare class here is exactly what clause 2.5 forbids.
            parent_name = equipment_class_parent_spare_class(addition.value)
            parent = SpareClass.objects.filter(
                name__iexact=parent_name, department=department
            ).first()
            if parent is None:
                continue
            _, made = EquipmentClass.objects.get_or_create(
                name=addition.value, spare_class=parent
            )
        created += 1 if made else 0
    return created


# ---------------------------------------------------------------------------------------
# The SHIP CUSTOMER CODE reconciliation, and the adopted-code resolver it depends on.
#
# Folded in from the former `services/customer_code.py` during the obs
# package-consolidation pass.
#
# The column is unique per ship, so every row must carry the same value and that value must
# be the active ship's own `Ship.customer_code`. A sheet that disagrees with the ship record
# was prepared for a different ship, and importing the agreeing rows would file part of one
# ship's inventory under another - the same reasoning that already makes the AUTHORITY
# mismatch a file-level refusal rather than a row flag.
#
# The value is reconciled and then DISCARDED, not stored. `obs.Spares` carries no customer
# code column and this change adds none - the value survives only as the leading segment of
# a generated pattern number, which is taken from the ship record.
#
# Rule 2.23.1's per-row check stays in the rule engine (`_check_ship_customer_code` above)
# untouched, exactly as rules 2.17.1 and 2.17.2 stayed there after the authority gate was
# added. The gate normally fires first - the rule remains where the register says it lives.
# ---------------------------------------------------------------------------------------


def ship_customer_code_mismatches(raw_rows, ship_customer_code):
    """Every row whose SHIP CUSTOMER CODE is not the active ship's own.

    Returns `[(row_number, what_the_cell_holds)]`. An empty cell is NOT reported here -
    rule 2.23.2 already fails that row on its own message, and reporting it twice in two
    voices helps nobody.
    """
    expected = (ship_customer_code or "").strip().upper()
    mismatched = []
    for row_number, row in raw_rows:
        held = cell_text(row.get("ship_customer_code")).strip().upper()
        if held and held != expected:
            mismatched.append((row_number, held))
    return mismatched


def ship_customer_code_mismatch_message(ship_customer_code, mismatched, limit=20):
    """The refusal sentence, naming the offending rows and what each of them holds.

    Developed by Unknown: reworded so the MO customer code is the FIRST thing the operator
    reads. It used to open "Rule 2.23 - the whole file is refused", which put a clause number
    where the answer belongs - the one question the operator has is which code this ship uses,
    and it was three clauses into the sentence. The rule number is dropped from the lead
    entirely. R-006's own per-row message keeps its clause prefix, so the register is not lost.
    The workbook's own code is named too, so both numbers are visible without reading the row
    list.
    """
    listed = mismatched[:limit]
    detail = ", ".join(f"row {number} holds {held}" for number, held in listed)
    if len(mismatched) > limit:
        detail = f"{detail}, and {len(mismatched) - limit} further row(s)"
    # Developed by Unknown: the first offending value, so the message can say what the workbook
    # carries as well as what the ship uses.
    carried = mismatched[0][1] if mismatched else ""
    return (
        f"MO customer code mismatch. This ship's MO customer code is {ship_customer_code}. "
        f"This workbook carries {carried}. The whole file is refused and nothing has been "
        f"loaded. {len(mismatched)} row(s) carry a different MO customer code - {detail}. "
        f"Check that this workbook was prepared for this ship, correct the SHIP CUSTOMER CODE "
        f"column, and import again."
    )


