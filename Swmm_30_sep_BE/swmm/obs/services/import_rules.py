def normalise_item_code(value):
    """The ONE normalisation applied to every pattern number, on BOTH sides of every compare.

    Returns the normalised code, or `None` where the value means "no pattern number".

    Developed by Unknown: This exists so the seeder, the four-source lookup and the near-match
    suggestion engine cannot drift apart. Three copies of a matching rule is how three callers
    end up disagreeing about whether two codes are the same code.

    What it does, and why each step is here:
      - strips a wrapping or leading single quote, which a text-mode export can leave on a
        value to stop a spreadsheet interpreting it
      - removes EVERY whitespace character, not just the ends. This is the change the user
        asked for: 46,618 codes across the two seeding files carry an internal space, and a
        rating typing the same code without it was previously told the pattern number did not
        exist
      - upper-cases, which is what makes the comparison case-insensitive without either side
        needing `__iexact`

    `str.split()` is used rather than a space-only replace because it takes the tab and the
    non-breaking space with it, and both reach these files from copy-and-paste.
    """
    text = "" if value is None else str(value)
    text = text.strip()
    if len(text) >= 2 and text.startswith("'") and text.endswith("'"):
        text = text[1:-1]
    elif text.startswith("'"):
        text = text[1:]
    normalised = "".join(text.split()).upper()
    if normalised in ITEM_CODE_JUNK_VALUES:
        return None
    return normalised


# Developed by Unknown: The same normalisation as `normalise_item_code`, expressed as a SQL
# expression so the two LIVE tables can be compared on equal terms with the workbook.
#
# `ILMS_item` and `WLMS_wlmsspare` are loaded from ILMS and WLMS respectively and this change
# adds no column to either, so there is nowhere to keep a pre-normalised copy. The two SOT
# tables need no equivalent - the seeder normalises before writing, so their `item_code`
# already IS the normalised form and a plain `__in` reaches it.
#
# `Replace` is nested rather than looped because it takes one search value at a time. Space,
# tab and non-breaking space are the three that occur; a wider set would cost a further scan
# per character for no measured benefit.
def _normalised_item_code_expression():
    expression = Upper("item_code")
    for whitespace in (" ", "\t", "\xa0"):
        expression = Replace(expression, Value(whitespace), Value(""))
    return expression


