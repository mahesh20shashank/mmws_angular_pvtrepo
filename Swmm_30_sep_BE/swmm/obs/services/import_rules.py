# Developed by Unknown: The working table, and why the server owns it.
#
# The results table on the References > Masters screen is now a WORKING table - a rating
# corrects a failing row in place and the row turns green by itself the moment it satisfies
# the rules. An edited row exists only in the browser, and both import endpoints are
# deliberately stateless and re-read the workbook from disk on every call, so an edit that
# never reached the server would be silently thrown away at commit time and the row would
# import with the value the user had already corrected.
#
# The client therefore sends its edits WITH the file, on both calls, and the server applies
# them to the parsed sheet before anything else looks at it. What the client sends is CELL
# VALUES, never a verdict - the rule engine, the source-of-truth cross-check, the serializer
# and `full_clean()` all run over the corrected sheet exactly as they run over an untouched
# one. Nothing a client can put in this payload can make a row pass a rule it fails.
#
# `authority` is deliberately NOT editable. The AUTHORITY column is a file-level gate
# checked against the authority the operator selected on the form, and a per-row edit to it
# could only ever refuse the whole file - which would take the working table away from the
# user rather than let them correct anything. The same reasoning excludes the SHIP CUSTOMER
# CODE column, which is reconciled against the active ship and is not shown in the table.
#
# The keys are the ones the results table itself renders - `_build_import_display_data`'s
# own field names - so the client edits what it can see. Three of them are named differently
# in the parsed sheet, because the header alias map points those columns at a `*_name`
# target that the payload builder resolves to a foreign key.
