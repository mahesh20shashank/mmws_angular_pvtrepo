"""The onboard-spares service layer, split into cohesive submodules.

`obs/services.py` was a single 2,923-line flat file holding five unrelated helper groups -
the import rule engine, master-value additions, the pattern-number cross-check, the SHIP
CUSTOMER CODE reconciliation and the issue/return/purge stock operations. This package
originally split it along those seams (`import_rules`, `master_additions`, `pattern`,
`customer_code`, `stock_ops`) with no behaviour change; the obs package-consolidation pass
later folded `master_additions`, `pattern` and `customer_code` back into `import_rules` -
all four were one thing, the import-row rule engine and everything it validates against -
leaving `import_rules` and `stock_ops` as the two modules here.

Every caller in this codebase reaches this layer through `from . import services` /
`from obs import services` and then `services.<name>` attribute access, never through
`from .services import <name>` - so this file re-exports every name any such caller reads,
and nothing about those call sites has to change.
"""

