from django.urls import path
from rest_framework.routers import DefaultRouter

from .views import (
    AuthorityViewSet,
    DemandViewSet,
    DenominationViewSet,
    EditMiscellaneousMasterDataView,
    EquipmentClassViewSet,
    IssueListViewSet,
    IssueViewSet,
    MiscellaneousMasterDataView,
    NotInCattedItemViewSet,
    PlannedRoutineSpareListViewSet,
    PostDemandViewSet,
    PostReceiveViewSet,
    PostSurveyViewSet,
    ReceiveViewSet,
    ReturnViewSet,
    RoutineSpareUsageViewSet,
    SpareClassViewSet,
    SparesMappingViewSet,
    SparesViewSet,
    SurveyViewSet,
)

app_name = "obs"

# Every `@action(detail=..., url_path=...)` on these viewsets (obs/views.py) only resolves
# correctly when the viewset is registered on a DRF router — the sub-routes (e.g.
# `spares/purge/`, `authorities/import-excel/`, `spares/d787j-deficiency/`) are generated by
# the router from those decorators. Matches the `DefaultRouter` + `router.register(prefix, ...)`
# convention already used elsewhere in the project (see e.g. ticket_manage/urls.py).
router = DefaultRouter()
router.register("spares", SparesViewSet)
router.register("spare-classes", SpareClassViewSet)
router.register("equipment-classes", EquipmentClassViewSet)
router.register("denominations", DenominationViewSet)
router.register("authorities", AuthorityViewSet)
router.register("routine-spare-usages", RoutineSpareUsageViewSet)
router.register("issues", IssueViewSet)
router.register("issue-list", IssueListViewSet)
router.register("returns", ReturnViewSet)
router.register("surveys", SurveyViewSet)
router.register("post-surveys", PostSurveyViewSet)
router.register("demands", DemandViewSet)
router.register("post-demands", PostDemandViewSet)
router.register("receives", ReceiveViewSet)
router.register("post-receives", PostReceiveViewSet)
router.register("planned-routine-spare-lists", PlannedRoutineSpareListViewSet)
router.register("spares-mappings", SparesMappingViewSet)
router.register("not-in-catted-items", NotInCattedItemViewSet)

# Legacy cascading-dropdown lookups (department -> spare class -> equipment class). Kept as
# manual bindings, distinct from the router's `spare-classes/`/`equipment-classes/` CRUD
# endpoints, because `obs/tests.py` still exercises these exact path shapes directly.
spare_classes = SpareClassViewSet.as_view({"get": "list", "post": "create"})
spare_classes_by_department = SpareClassViewSet.as_view({"get": "by_department"})
equipment_classes = EquipmentClassViewSet.as_view({"get": "list", "post": "create"})
equipment_classes_by_spare = EquipmentClassViewSet.as_view({"get": "by_spare_class"})
equipment_classes_department_master = EquipmentClassViewSet.as_view(
    {"get": "department_master"}
)

urlpatterns = [
    path("miscellaneous/", MiscellaneousMasterDataView.as_view(), name="miscellaneous"),
    path(
        "edit_miscellaneous/",
        EditMiscellaneousMasterDataView.as_view(),
        name="edit_miscellaneous",
    ),
    path("spare_class/", spare_classes, name="spare_class"),
    path(
        "spare_class/<int:department_id>/",
        spare_classes_by_department,
        name="spare_class_pk",
    ),
    path("equipment_class/", equipment_classes, name="equipment_class"),
    # Placed ABOVE `equipment_class/<int:department_id>/<int:spare_class_id>/`, which is
    # int-typed and could not have matched `department-master` anyway - kept explicit so a
    # later change to that converter cannot shadow this route.
    path(
        "equipment_class/department-master/",
        equipment_classes_department_master,
        name="equipment_class_department_master",
    ),
    path(
        "equipment_class/<int:department_id>/<int:spare_class_id>/",
        equipment_classes_by_spare,
        name="equipment_class_pk",
    ),
] + router.urls
